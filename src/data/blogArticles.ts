// ─── Helper functions ───

export function getArticleBySlug(categorySlug: string, slug: string): BlogArticle | undefined {
  return blogArticles.find(a => a.categorySlug === categorySlug && a.slug === slug);
}

export function getArticlesByCategory(categorySlug: string): BlogArticle[] {
  return blogArticles.filter(a => a.categorySlug === categorySlug);
}

export function getRelatedArticles(article: BlogArticle): BlogArticle[] {
  return article.relatedSlugs
    .map(slug => blogArticles.find(a => a.slug === slug))
    .filter((a): a is BlogArticle => !!a)
    .slice(0, 3);
}
